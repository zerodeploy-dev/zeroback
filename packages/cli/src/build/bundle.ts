import * as path from "path";
import * as fs from "fs";
import type { SchemaJSON } from "@zeroback/server";

function scanFiles(dir: string, rootDir: string): { relPath: string; moduleName: string }[] {
  const results: { relPath: string; moduleName: string }[] = [];
  const seen = new Set<string>();

  function walk(d: string): void {
    for (const entry of fs.readdirSync(d)) {
      if (entry.startsWith("_") || entry === "node_modules") continue;
      const fullPath = path.join(d, entry);

      if (fs.statSync(fullPath).isDirectory()) {
        walk(fullPath);
        continue;
      }

      if (entry.endsWith(".d.ts") || entry.endsWith(".map")) continue;
      if (entry.endsWith(".test.ts") || entry.endsWith(".spec.ts")) continue;
      if (!entry.endsWith(".ts") && !entry.endsWith(".js")) continue;
      const baseName = path.basename(entry, path.extname(entry));

      // Skip special top-level files (schema, http, crons, auth) only at the root
      if (d === rootDir) {
        if (baseName === "schema" || baseName === "http" || baseName === "crons" || baseName === "auth") continue;
      }

      const relPath = path.relative(rootDir, fullPath).replace(/\\/g, "/");
      // Convert path separators to dots for namespace hierarchy (e.g., "inbox/threads" → "inbox.threads")
      const moduleName = relPath.replace(/\.(ts|js)$/, "").replace(/\//g, ".");

      // Deduplicate: prefer .ts over .js
      if (seen.has(moduleName)) continue;
      seen.add(moduleName);
      results.push({ relPath, moduleName });
    }
  }

  walk(dir);
  return results;
}

export function toSafeName(moduleName: string): string {
  return moduleName.replace(/\//g, "$").replace(/[^a-zA-Z0-9_$]/g, "_");
}

/**
 * Generate _generated/manifest.ts that exports functions, schema, httpRouter, and cronJobsDef.
 * The static .zeroback/entry.ts imports from this manifest to wire everything to the runtime.
 */
export async function bundle(functionsDir: string, schema?: SchemaJSON): Promise<void> {
  const files = scanFiles(functionsDir, functionsDir);

  // Check if user has an http.ts file for HTTP actions
  const hasHttpFile = fs.existsSync(path.join(functionsDir, "http.ts")) || fs.existsSync(path.join(functionsDir, "http.js"));

  // Check if user has a crons.ts file for cron jobs
  const hasCronsFile = fs.existsSync(path.join(functionsDir, "crons.ts")) || fs.existsSync(path.join(functionsDir, "crons.js"));

  // Check if user has an auth.ts file for built-in auth
  const hasAuthFile = fs.existsSync(path.join(functionsDir, "auth.ts")) || fs.existsSync(path.join(functionsDir, "auth.js"));

  // Import paths are relative from _generated/ to the parent functionsDir (one level up)
  const imports: string[] = [];
  const registrations: string[] = [];
  const usedNames = new Set<string>();

  for (const { relPath, moduleName } of files) {
    let safeName = toSafeName(moduleName);
    if (usedNames.has(safeName)) {
      let suffix = 2;
      while (usedNames.has(`${safeName}_${suffix}`)) suffix++;
      safeName = `${safeName}_${suffix}`;
    }
    usedNames.add(safeName);
    // Use relPath (with /) for import path, moduleName (with .) for function registry
    const importPath = relPath.replace(/\.(ts|js)$/, "");
    imports.push(`import * as ${safeName} from "../${importPath}";`);
    registrations.push(
      `for (const [name, fn] of Object.entries(${safeName})) {`,
      `  if (fn && typeof fn === "object" && "_type" in fn && "handler" in fn) {`,
      `    const f = fn as Record<string, unknown>;`,
      `    const argsValidator = "_argsValidator" in fn ? f._argsValidator as FunctionDef["argsValidator"] : undefined;`,
      `    const returnsValidator = "_returnsValidator" in fn ? f._returnsValidator as FunctionDef["returnsValidator"] : undefined;`,
      `    const isInternal = "_isInternal" in fn ? !!f._isInternal : false;`,
      `    functions["${moduleName}:" + name] = { type: f._type as FunctionDef["type"], isInternal, handler: f.handler as FunctionDef["handler"], argsValidator, returnsValidator };`,
      `  }`,
      `}`
    );
  }

  // Import HTTP router if present
  const httpImport = hasHttpFile
    ? [`import httpRouterModule from "../http";`]
    : [];

  // Import cron jobs if present
  const cronsImport = hasCronsFile
    ? [`import cronsModule from "../crons";`]
    : [];

  // Import auth if present
  const authImport = hasAuthFile
    ? [`import * as authModule from "../auth";`]
    : [];

  const content = [
    `// Auto-generated by zeroback CLI — DO NOT EDIT`,
    `import type { FunctionDef } from "@zeroback/server/runtime";`,
    `import type { SchemaJSON } from "@zeroback/server";`,
    ...imports,
    ...httpImport,
    ...cronsImport,
    ...authImport,
    ``,
    `const functions: Record<string, FunctionDef> = {};`,
    ``,
    ...registrations,
    ``,
    `export const schema = ${JSON.stringify(schema ?? { tables: {} })} as SchemaJSON;`,
    ``,
    `export { functions };`,
    `export const httpRouter = ${hasHttpFile ? "httpRouterModule" : "null"};`,
    `export const cronJobsDef = ${hasCronsFile ? "cronsModule" : "null"};`,
    `export const authDef = ${hasAuthFile ? "(authModule as { auth?: unknown }).auth ?? null" : "null"};`,
    ``,
  ].join("\n");

  const outfile = path.join(functionsDir, "_generated", "manifest.ts");
  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  fs.writeFileSync(outfile, content);
}
