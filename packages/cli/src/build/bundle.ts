import * as path from "path";
import * as fs from "fs";
import type { SchemaJSON } from "@vex/server";

function scanFiles(dir: string, rootDir: string): { relPath: string; moduleName: string }[] {
  const results: { relPath: string; moduleName: string }[] = [];

  for (const entry of fs.readdirSync(dir)) {
    if (entry.startsWith("_") || entry === "node_modules") continue;
    const fullPath = path.join(dir, entry);

    if (fs.statSync(fullPath).isDirectory()) {
      results.push(...scanFiles(fullPath, rootDir));
      continue;
    }

    if (!entry.endsWith(".ts") && !entry.endsWith(".js")) continue;
    const baseName = path.basename(entry, path.extname(entry));

    // Skip special top-level files (schema, http, crons) only at the root
    if (dir === rootDir) {
      if (baseName === "schema" || baseName === "http" || baseName === "crons") continue;
    }

    const relPath = path.relative(rootDir, fullPath).replace(/\\/g, "/");
    const moduleName = relPath.replace(/\.(ts|js)$/, "");
    results.push({ relPath, moduleName });
  }

  return results;
}

/**
 * Generate a _functions.generated.ts that imports user functions.
 * Wrangler's own bundler will handle resolution and bundling.
 */
export async function bundle(vexDir: string, outfile: string, schema?: SchemaJSON): Promise<void> {
  const files = scanFiles(vexDir, vexDir);

  // Check if user has an http.ts file for HTTP actions
  const hasHttpFile = fs.existsSync(path.join(vexDir, "http.ts")) || fs.existsSync(path.join(vexDir, "http.js"));

  // Check if user has a crons.ts file for cron jobs
  const hasCronsFile = fs.existsSync(path.join(vexDir, "crons.ts")) || fs.existsSync(path.join(vexDir, "crons.js"));

  // Compute relative path from outfile's directory to vex dir
  const outDir = path.dirname(outfile);
  const relVex = path.relative(outDir, vexDir).replace(/\\/g, "/");

  const imports: string[] = [];
  const registrations: string[] = [];

  for (const { moduleName } of files) {
    const safeName = moduleName.replace(/[^a-zA-Z0-9]/g, "_");
    imports.push(`import * as ${safeName} from "${relVex}/${moduleName}";`);
    registrations.push(
      `for (const [name, fn] of Object.entries(${safeName})) {`,
      `  if (fn && typeof fn === "object" && "_type" in fn && "handler" in fn) {`,
      `    const argsValidator = "_argsValidator" in fn ? (fn as any)._argsValidator : undefined;`,
      `    const returnsValidator = "_returnsValidator" in fn ? (fn as any)._returnsValidator : undefined;`,
      `    const isInternal = "_isInternal" in fn ? !!(fn as any)._isInternal : false;`,
      `    functions["${moduleName}:" + name] = { type: (fn as any)._type, isInternal, handler: (fn as any).handler, argsValidator, returnsValidator };`,
      `  }`,
      `}`
    );
  }

  // Import HTTP router if present
  const httpImport = hasHttpFile
    ? [`import httpRouterModule from "${relVex}/http";`]
    : [];
  const httpExport = hasHttpFile
    ? [`export const httpRouter = httpRouterModule;`]
    : [`export const httpRouter = null;`];

  // Import cron jobs if present
  const cronsImport = hasCronsFile
    ? [`import cronsModule from "${relVex}/crons";`]
    : [];
  const cronsExport = hasCronsFile
    ? [`export const cronJobsDef = cronsModule;`]
    : [`export const cronJobsDef = null;`];

  const content = [
    `// Auto-generated by vex CLI — DO NOT EDIT`,
    ...imports,
    ...httpImport,
    ...cronsImport,
    ``,
    `type FunctionDef = {`,
    `  type: "query" | "mutation" | "action";`,
    `  isInternal: boolean;`,
    `  handler: (ctx: any, args: any) => Promise<any>;`,
    `  argsValidator?: Record<string, { json: any }>;`,
    `  returnsValidator?: { json: any };`,
    `};`,
    `export const functions: Record<string, FunctionDef> = {};`,
    ``,
    ...registrations,
    ``,
    `export const schema = ${JSON.stringify(schema ?? { tables: {} })};`,
    ``,
    ...httpExport,
    ``,
    ...cronsExport,
    ``,
  ].join("\n");

  fs.mkdirSync(path.dirname(outfile), { recursive: true });
  fs.writeFileSync(outfile, content);
}
